"""写出根目录的 WinUI 3 启动器（.bat），严格控制字节。

为什么用脚本生成而不是直接写文件：**行尾必须是 CRLF**。

cmd.exe 解析 .bat 时不把 LF 当行分隔符处理到底，遇到多行 if (...) 块会把
下一行粘进来——实测症状是 REM 被读成 ROJ、pause 和 if 拼成一条命令、
整个脚本行为完全错乱。仓库里原有的 .bat 也是 LF，但它们只有单行 if/else，
侥幸没踩到；这个启动器有嵌套 if，必须用 CRLF。

同样不能用 UTF-8 BOM：cmd.exe 见到 BOM 会把第一行当成命令的一部分。

用法::

    python winui\\tools\\make_launcher.py
"""

import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
OUT = os.path.join(ROOT, "启动 WinUI 3 界面.bat")

# 正文全部用 ASCII：chcp 65001 之后的 echo 汉字才可靠，
# 而注释和命令在切换代码页之前就被解析了。
BODY = """@echo off
REM Dump Search - WinUI 3 GUI launcher
REM Generated by winui\\tools\\make_launcher.py -- edit that, not this file.
REM
REM Why a launcher instead of pointing the shortcut straight at the exe:
REM the exe lives under bin\\Release\\<tfm>\\, a path that depends on build
REM config. Change Release to Debug and a direct shortcut points at nothing.
REM This script looks for the exe every launch and builds only if missing.
setlocal
cd /d "%~dp0"
chcp 65001 >nul
set PYTHONIOENCODING=utf-8

set "PROJ=winui\\src\\DumpSearch.App"
set "EXE=%PROJ%\\bin\\Release\\net8.0-windows10.0.19041.0\\DumpSearch.exe"
set "EXED=%PROJ%\\bin\\Debug\\net8.0-windows10.0.19041.0\\DumpSearch.exe"

if exist "%EXE%" goto launch
if exist "%EXED%" set "EXE=%EXED%" & goto launch

echo First run: building the WinUI 3 app, please wait...
echo.
where dotnet >nul 2>nul
if errorlevel 1 goto nodotnet
pushd "%PROJ%"
dotnet build -c Release
popd
if exist "%EXE%" goto launch
goto buildfailed

:launch
start "" "%EXE%" %*
endlocal
exit /b 0

:nodotnet
echo [ERROR] dotnet not found. Please install the .NET 8 SDK or newer.
pause
endlocal
exit /b 1

:buildfailed
echo.
echo [ERROR] Build failed. See the output above.
pause
endlocal
exit /b 1
"""


def main() -> int:
    # newline="" 阻止 Python 把 \n 再翻成 \r\n；行分隔符由文本里写死的 \r\n 负责
    with open(OUT, "w", encoding="ascii", newline="") as f:
        f.write(BODY.replace("\r\n", "\n").replace("\n", "\r\n"))

    size = os.path.getsize(OUT)
    with open(OUT, "rb") as f:
        raw = f.read()
    crlf = raw.count(b"\r\n")
    lf = raw.count(b"\n")
    print(f"已生成启动器: {OUT}")
    print(f"  大小 {size} B   CRLF {crlf} 行 / LF 总数 {lf}")
    if lf != crlf:
        print("  [警告] 存在裸 LF，cmd.exe 会错行解析")
        return 1
    if raw.startswith(b"\xef\xbb\xbf"):
        print("  [警告] 文件带 BOM，cmd.exe 会把第一行解析错")
        return 1
    print("  行尾与 BOM 检查通过")
    return 0


if __name__ == "__main__":
    sys.exit(main())
